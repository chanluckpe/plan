/* 슛 길목에 수비가 서 있으면 막혀요 (플로어볼·라크로스) */
function shotBlock(ctx, f, reachK = .85) {
  if (!f.K.shot) return false;
  const { P, pos, M } = ctx, a = f.pts[0], b = f.pts[f.pts.length - 1], L = dist(a, b);
  for (let j = 0; j < P.length; j++) {
    if (P[j].t === f.team || ctx.st[j].out || /^(GK|G)$/.test(P[j].pos)) continue;
    const q = pos[j], d0 = dist(q, a);
    if (d0 > L * reachK || d0 < .5 * M) continue;
    if (segDist(q, a, b) < .6 * M) {
      ctx.ball.flight = null; ctx.ball.rest = [q[0] + (a[0] - q[0]) * .2, q[1] + (a[1] - q[1]) * .2];
      ctx.call('슛 블록!', q, { color: '#38bdf8' }); return true;
    }
  }
  return false;
}
